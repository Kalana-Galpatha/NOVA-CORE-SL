// Builds src/lib/worldPath.js: one compact SVG path of the world's land (Natural Earth 110m),
// drawn on a 360 x 180 equirectangular canvas (x = lon + 180, y = 90 - lat).
// Run once: node scripts/make-world-path.mjs   (needs the world-atlas and topojson-client dev dependencies)
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/land-110m.json');
const land = feature(topo, topo.objects.land);
const r = (n) => Math.round(n * 10) / 10;
let d = '';
const rings = (geom) => (geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates).flat();
for (const f of land.features ?? [land]) {
  for (const ring of rings(f.geometry ?? f)) {
    ring.forEach(([lon, lat], i) => { d += `${i ? 'L' : 'M'}${r(lon + 180)} ${r(90 - lat)}`; });
    d += 'Z';
  }
}
fs.writeFileSync('src/lib/worldPath.js', `// Generated by scripts/make-world-path.mjs from Natural Earth 110m land (public domain).\nexport const WORLD_PATH = '${d}';\n`);
console.log('path chars:', d.length);
